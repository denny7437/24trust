export const isPlaceholder = (value: string) => /^\[.*\]$/.test(value.trim());

/** Ник из записи nagaevofficial, @nagaevofficial или t.me/nagaevofficial. Пустая строка — если это не ник. */
export function telegramHandle(value: string) {
  const handle = value
    .trim()
    .replace(/^(?:https?:\/\/)?(?:t|telegram)\.me\//i, '')
    .replace(/^@/, '')
    .replace(/\/+$/, '');
  return /^[A-Za-z][A-Za-z0-9_]{4,31}$/.test(handle) ? handle : '';
}

/** Ссылка tel: из любой записи номера. Пустая строка — если номер не распознан. */
export function phoneHref(value: string) {
  const number = value.replace(/[^\d+]/g, '');
  return /^\+?\d{10,15}$/.test(number) ? `tel:${number}` : '';
}

